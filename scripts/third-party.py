"""Regenerates THIRD_PARTY.md: every Rust crate compiled into the app (Linux and Windows
targets) and every npm package bundled into the frontend, with its license
(CLEAN-ROOM.md rule 6). Non-code third-party material is listed in the header section.

Usage: python3 scripts/third-party.py > THIRD_PARTY.md
"""
import json
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TARGETS = ["x86_64-unknown-linux-gnu", "x86_64-pc-windows-msvc"]


def rust_crates():
    meta = json.loads(subprocess.check_output(
        ["cargo", "metadata", "--format-version", "1", "--locked"], cwd=ROOT))
    pkgs = {p["id"]: p for p in meta["packages"]}
    names = set()
    for target in TARGETS:
        out = subprocess.check_output(
            ["cargo", "tree", "--workspace", "-e", "normal", "--prefix", "none",
             "--target", target, "--format", "{p}"], cwd=ROOT, text=True)
        for line in out.splitlines():
            parts = line.split()
            if len(parts) >= 2:
                names.add((parts[0], parts[1].lstrip("v")))
    rows = []
    for p in pkgs.values():
        if (p["name"], p["version"]) in names and p["source"]:
            rows.append((p["name"], p["version"], p.get("license") or p.get("license_file") or "UNKNOWN"))
    return sorted(set(rows))


def npm_packages():
    lock = json.loads((ROOT / "package-lock.json").read_text())
    pkg = json.loads((ROOT / "package.json").read_text())
    rows = []
    for name in pkg.get("dependencies", {}):
        stack = [name]
        seen = set()
        while stack:
            n = stack.pop()
            if n in seen:
                continue
            seen.add(n)
            info = lock["packages"].get(f"node_modules/{n}", {})
            lic = info.get("license")
            if not lic:
                # Older packages declare `licenses: [{type: ...}]` (read from the package).
                pj = ROOT / "node_modules" / n / "package.json"
                if pj.exists():
                    meta = json.loads(pj.read_text())
                    lic = meta.get("license") or " OR ".join(
                        l.get("type", "") for l in meta.get("licenses", []) if isinstance(l, dict)) or None
            rows.append((n, info.get("version", "?"), lic or "UNKNOWN"))
            stack.extend(info.get("dependencies", {}).keys())
    return sorted(set(rows))


def table(rows):
    out = ["| Package | Version | License |", "|---|---|---|"]
    out += [f"| {n} | {v} | {l} |" for n, v, l in rows]
    return "\n".join(out)


rust = rust_crates()
npm = npm_packages()
